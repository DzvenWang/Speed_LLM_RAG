def parse_int_list(text: str | None, default: Iterable[int]) -> List[int]:
    if text is None:
        return list(default)
    return [int(x.strip()) for x in str(text).split(",") if x.strip()]


def parse_str_list(text: str | None, default: Iterable[str]) -> List[str]:
    if text is None:
        return list(default)
    return [x.strip() for x in str(text).split(",") if x.strip()]


def add_inference_features(df: pd.DataFrame) -> pd.DataFrame:
    """Feature engineering restricted to inference-available fields.

    The input table may contain diagnostic labels, but none of those columns are copied into
    the returned model feature list. Candidate IDs are retained for action execution only and
    are never used directly as numerical features.
    """
    x = df.copy()
    required_defaults = {
        "score": np.nan, "level_mae": np.nan, "delta_mae": np.nan,
        "overlap_fraction": np.nan, "tod_distance": np.nan, "dow_match": np.nan,
        "patch_restorable_count": np.nan, "patch_observed_count": np.nan,
        "rank": np.nan, "patch_id": np.nan, "recent_steps": np.nan,
    }
    for c, v in required_defaults.items():
        if c not in x:
            x[c] = v

    # Retrieval geometry.
    x["rank_inv"] = 1.0 / np.maximum(x["rank"].astype(float), 1.0)
    x["rank_log"] = np.log1p(np.maximum(x["rank"].astype(float), 0.0))
    x["level_delta_gap"] = x["level_mae"].astype(float) - x["delta_mae"].astype(float)
    x["level_delta_ratio"] = x["level_mae"].astype(float) / np.maximum(x["delta_mae"].astype(float), 1e-6)
    x["tod_closeness"] = 1.0 - np.clip(x["tod_distance"].astype(float), 0.0, 1.0)
    x["scope_fraction"] = x["recent_steps"].astype(float) / 12.0
    x["scope_log"] = np.log1p(np.maximum(x["recent_steps"].astype(float), 0.0))
    x["patch_missing_to_observed"] = x["patch_restorable_count"].astype(float) / np.maximum(
        x["patch_observed_count"].astype(float), 1.0
    )
    x["patch_total_evidence"] = x["patch_restorable_count"].astype(float) + x["patch_observed_count"].astype(float)
    x["patch_missing_fraction_proxy"] = x["patch_restorable_count"].astype(float) / np.maximum(
        x["patch_total_evidence"].astype(float), 1.0
    )

    # Within-query/patch retrieval-relative signals. These are especially useful because
    # absolute distance scales differ by traffic regime and patch.
    group = ["query_id", "patch_id"]
    for c in ["score", "level_mae", "delta_mae"]:
        vals = x[c].astype(float)
        gmin = x.groupby(group, sort=False)[c].transform("min").astype(float)
        gmean = x.groupby(group, sort=False)[c].transform("mean").astype(float)
        gstd = x.groupby(group, sort=False)[c].transform("std").astype(float).fillna(0.0)
        x[f"{c}_minus_best"] = vals - gmin
        x[f"{c}_minus_mean"] = vals - gmean
        x[f"{c}_z"] = (vals - gmean) / np.maximum(gstd, 1e-6)

    # Current-query patch descriptors generated by the dataset builder.
    # They are optional so synthetic tests can stay compact.
    optional = [
        "query_patch_observed_fraction", "query_patch_missing_fraction_scope",
        "query_patch_obs_mean", "query_patch_obs_std", "query_patch_recent_mean",
        "query_patch_recent_std", "query_patch_delta_abs_mean",
        "candidate_patch_mean", "candidate_patch_std", "candidate_patch_recent_mean",
        "candidate_patch_recent_std", "candidate_patch_delta_abs_mean",
        "candidate_query_mean_gap", "candidate_query_std_gap", "candidate_query_delta_gap",
        "affine_scale", "affine_shift", "affine_overlap_points", "proposed_fill_count",
        "proposal_abs_change_mean", "proposal_abs_change_max",
    ]
    for c in optional:
        if c not in x:
            x[c] = np.nan

    # Categorical identities are one-hot encoded as compact deterministic numeric columns.
    # Patch identity is legal at inference and captures systematic local heterogeneity.
    patch_vals = sorted(int(v) for v in pd.Series(x["patch_id"]).dropna().unique())
    for p in patch_vals:
        x[f"patch_is_{p}"] = (x["patch_id"].astype(float) == float(p)).astype(float)
    scope_vals = sorted(int(v) for v in pd.Series(x["recent_steps"]).dropna().unique())
    for s in scope_vals:
        x[f"scope_is_{s}"] = (x["recent_steps"].astype(float) == float(s)).astype(float)

    x.replace([np.inf, -np.inf], np.nan, inplace=True)
    return x


def feature_columns(df: pd.DataFrame) -> List[str]:
    base = [
        "score", "level_mae", "delta_mae", "overlap_fraction", "tod_distance", "tod_closeness", "dow_match",
        "rank_inv", "rank_log", "level_delta_gap", "level_delta_ratio",
        "scope_fraction", "scope_log", "patch_observed_count",
        "patch_missing_to_observed", "patch_missing_fraction_proxy", "patch_total_evidence",
        "score_minus_best", "score_minus_mean", "score_z",
        "level_mae_minus_best", "level_mae_minus_mean", "level_mae_z",
        "delta_mae_minus_best", "delta_mae_minus_mean", "delta_mae_z",
        "query_patch_observed_fraction", "query_patch_missing_fraction_scope",
        "query_patch_obs_mean", "query_patch_obs_std", "query_patch_recent_mean",
        "query_patch_recent_std", "query_patch_delta_abs_mean",
        "candidate_patch_mean", "candidate_patch_std", "candidate_patch_recent_mean",
        "candidate_patch_recent_std", "candidate_patch_delta_abs_mean",
        "candidate_query_mean_gap", "candidate_query_std_gap", "candidate_query_delta_gap",
        "affine_scale", "affine_shift", "affine_overlap_points", "proposed_fill_count",
        "proposal_abs_change_mean", "proposal_abs_change_max",
    ]
    base += sorted([c for c in df.columns if c.startswith("patch_is_") or c.startswith("scope_is_")])
    cols = [c for c in base if c in df.columns and c not in LABEL_COLUMNS and not df[c].isna().all()]
    forbidden_fragments = ["forecast", "completion_mae", "beneficial", "harmful"]
    bad = [c for c in cols if any(f in c for f in forbidden_fragments)]
    if bad:
        raise RuntimeError(f"Leakage-prone features unexpectedly included: {bad}")
    return cols


@dataclass
class SelectorModel:
    name: str
    task: str
    estimator: object | None = None
    gate_estimator: object | None = None
    utility_estimator: object | None = None


def _histgb_reg(seed: int):
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("model", HistGradientBoostingRegressor(
            max_iter=220, max_leaf_nodes=31, max_depth=6, learning_rate=0.045,
            min_samples_leaf=40, l2_regularization=1.0, random_state=int(seed),
        )),
    ])


def _histgb_cls(seed: int):
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("model", HistGradientBoostingClassifier(
            max_iter=180, max_leaf_nodes=31, max_depth=5, learning_rate=0.05,
            min_samples_leaf=40, l2_regularization=1.0, random_state=int(seed),
        )),
    ])


def make_model(name: str, seed: int) -> SelectorModel:
    name = str(name)
    if name == "similarity_rule":
        return SelectorModel(name, "rule")
    if name == "logistic_gate":
        est = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("scale", StandardScaler()),
            ("model", LogisticRegression(max_iter=800, class_weight="balanced", random_state=int(seed))),
        ])
        return SelectorModel(name, "classification", estimator=est)
    if name == "ridge_utility":
        est = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("scale", StandardScaler()),
            ("model", Ridge(alpha=3.0)),
        ])
        return SelectorModel(name, "regression", estimator=est)
    if name == "histgb_utility":
        return SelectorModel(name, "regression", estimator=_histgb_reg(seed))
    if name == "mlp_utility":
        est = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("scale", StandardScaler()),
            ("model", MLPRegressor(
                hidden_layer_sizes=(96, 48), activation="relu", alpha=3e-4,
                learning_rate_init=8e-4, max_iter=120, early_stopping=True,
                validation_fraction=0.12, n_iter_no_change=10, random_state=int(seed),
            )),
        ])
        return SelectorModel(name, "regression", estimator=est)
    if name == "two_stage_histgb":
        return SelectorModel(name, "two_stage", gate_estimator=_histgb_cls(seed), utility_estimator=_histgb_reg(seed + 101))
    raise KeyError(f"Unknown selector model: {name}")


def fit_model(spec: SelectorModel, train_df: pd.DataFrame, features: List[str]) -> SelectorModel:
    if spec.task == "rule":
        return spec
    X = train_df[features].to_numpy(np.float64)
    y_u = train_df["forecast_utility"].to_numpy(np.float64)
    y_b = (y_u > 0.0).astype(np.int64)
    if spec.task == "classification":
        if np.unique(y_b).size < 2:
            spec.task = "constant_classification"; spec.estimator = float(np.mean(y_b)); return spec
        spec.estimator.fit(X, y_b); return spec
    if spec.task == "regression":
        spec.estimator.fit(X, y_u); return spec
    if spec.task == "two_stage":
        if np.unique(y_b).size < 2:
            spec.gate_estimator = float(np.mean(y_b))
        else:
            spec.gate_estimator.fit(X, y_b)
        spec.utility_estimator.fit(X, y_u)
        return spec
    raise KeyError(spec.task)


def predict_scores(spec: SelectorModel, df: pd.DataFrame, features: List[str]) -> np.ndarray:
    if spec.task == "rule":
        # Retrieval score is a distance: smaller is better. Tiny tie-breaks favor earlier ranks.
        return -df["score"].to_numpy(np.float64) - 1e-9 * df["rank"].to_numpy(np.float64)
    if spec.task == "constant_classification":
        return np.full(len(df), float(spec.estimator), np.float64)
    X = df[features].to_numpy(np.float64)
    if spec.task == "classification":
        return np.asarray(spec.estimator.predict_proba(X)[:, 1], np.float64)
    if spec.task == "regression":
        return np.asarray(spec.estimator.predict(X), np.float64)
    if spec.task == "two_stage":
        if isinstance(spec.gate_estimator, float):
            p = np.full(len(df), float(spec.gate_estimator), np.float64)
        else:
            p = np.asarray(spec.gate_estimator.predict_proba(X)[:, 1], np.float64)
        u = np.asarray(spec.utility_estimator.predict(X), np.float64)
        # This score rewards actions that are both likely beneficial and predicted to have positive magnitude.
        return p * np.maximum(u, 0.0) + 0.05 * p * np.maximum(np.nanstd(u), 1e-6)
    raise KeyError(spec.task)


def expanding_time_folds(query_order: Iterable[int], n_blocks: int = 6):
    """Strict causal folds: fit on old blocks, calibrate on the immediately previous block,
    and test only on a later block. No future utility labels can enter fit/calibration.
    """
    qids = np.asarray(list(dict.fromkeys(map(int, query_order))), np.int64)
    if len(qids) < 12:
        raise ValueError("Need at least 12 ordered queries for expanding temporal CV")
    n_blocks = max(4, min(int(n_blocks), len(qids) // 2))
    blocks = [np.asarray(b, np.int64) for b in np.array_split(qids, n_blocks) if len(b)]
    for test_idx in range(2, len(blocks)):
        fit = np.concatenate(blocks[:test_idx - 1])
        calib = blocks[test_idx - 1]
        test = blocks[test_idx]
        yield test_idx - 2, fit, calib, test


def blocked_folds(query_order: Iterable[int], n_splits: int = 5):
    qids = np.asarray(list(dict.fromkeys(map(int, query_order))), np.int64)
    n_splits = max(2, min(int(n_splits), len(qids)))
    blocks = [np.asarray(b, np.int64) for b in np.array_split(qids, n_splits) if len(b)]
    for i, test in enumerate(blocks):
        train = np.concatenate([b for j, b in enumerate(blocks) if j != i])
        # Calibration is a deterministic trailing portion of train; this protocol is diagnostic only.
        ncal = max(1, int(round(0.15 * len(train))))
        yield i, train[:-ncal], train[-ncal:], test


def select_best_per_patch(df: pd.DataFrame, scores: np.ndarray, max_k: int) -> pd.DataFrame:
    w = df[df["rank"] <= int(max_k)].copy()
    if len(w) == 0:
        return w.assign(_score=np.array([], dtype=float))
    # scores was produced for the unfiltered df in the normal path; align by index.
    score_series = pd.Series(np.asarray(scores, np.float64), index=df.index)
    w["_score"] = score_series.loc[w.index].to_numpy(np.float64)
    w = w.sort_values(
        ["query_id", "recent_steps", "patch_id", "_score", "rank"],
        ascending=[True, True, True, False, True], kind="mergesort"
    )
    return w.groupby(["query_id", "recent_steps", "patch_id"], sort=False, as_index=False).head(1).copy()


def tune_gate_and_cap(calib_df: pd.DataFrame, scores: np.ndarray, max_k: int,
                      patch_caps: Iterable[int] = (1, 2, 4, 6, 8, 12, 16)) -> Dict[str, float]:
    """Tune abstention threshold and max patches using only calibration action labels.

    The objective is additive single-patch utility. It deliberately avoids future test labels and
    avoids an expensive PatchSTG grid search. End-to-end interaction is measured only after the
    decision rule is frozen and applied to the test block.
    """
    top = select_best_per_patch(calib_df, scores, max_k)
    if top.empty:
        return {"threshold": float("inf"), "max_patches": 0, "calib_additive_utility": 0.0,
                "calib_intervention_rate": 0.0, "calib_patch_precision": float("nan")}
    finite = top["_score"].to_numpy(np.float64)
    finite = finite[np.isfinite(finite)]
    if finite.size == 0:
        thresholds = [float("inf")]
    else:
        thresholds = np.unique(np.quantile(finite, np.linspace(0.0, 1.0, 81))).tolist()
        thresholds = [-float("inf")] + thresholds + [float("inf")]
    caps = sorted(set(max(1, int(c)) for c in patch_caps))
    best = None
    groups = list(top.groupby(["query_id", "recent_steps"], sort=False))
    for cap in caps:
        for tau in thresholds:
            total_u = 0.0; selected = 0; good = 0; group_count = 0
            for _, g in groups:
                z = g[np.isfinite(g["_score"]) & (g["_score"] > float(tau))].sort_values("_score", ascending=False)
                z = z.head(cap)
                u = z["forecast_utility"].to_numpy(np.float64)
                total_u += float(np.sum(u)); selected += len(z); good += int(np.sum(u > 0)); group_count += 1
            mean_u = total_u / max(group_count, 1)
            # Prefer higher utility, then fewer selected actions, then higher threshold.
            key = (mean_u, -selected, float(tau))
            if best is None or key > best[0]:
                best = (key, tau, cap, mean_u, selected, good, group_count)
    assert best is not None
    _, tau, cap, mean_u, selected, good, group_count = best
    return {
        "threshold": float(tau), "max_patches": int(cap), "calib_additive_utility": float(mean_u),
        "calib_intervention_rate": float(selected / max(group_count, 1)),
        "calib_patch_precision": float(good / selected) if selected else float("nan"),
    }


def apply_decision_rule(df: pd.DataFrame, scores: np.ndarray, max_k: int, threshold: float, max_patches: int) -> pd.DataFrame:
    top = select_best_per_patch(df, scores, max_k)
    if top.empty:
        return top
    top = top[np.isfinite(top["_score"]) & (top["_score"] > float(threshold))].copy()
    if top.empty:
        return top
    top = top.sort_values(["query_id", "recent_steps", "_score", "rank"], ascending=[True, True, False, True])
    return top.groupby(["query_id", "recent_steps"], sort=False, as_index=False).head(int(max_patches)).copy()


def action_metrics(df: pd.DataFrame, scores: np.ndarray) -> Dict[str, float]:
    y = (df["forecast_utility"].to_numpy(np.float64) > 0.0).astype(np.int64)
    s = np.asarray(scores, np.float64)
    good = np.isfinite(s)
    out = {"action_rows": int(good.sum()), "beneficial_rate": float(np.mean(y[good])) if np.any(good) else float("nan")}
    if np.any(good) and np.unique(y[good]).size > 1:
        out["action_roc_auc"] = float(roc_auc_score(y[good], s[good]))
        out["action_average_precision"] = float(average_precision_score(y[good], s[good]))
    else:
        out["action_roc_auc"] = float("nan"); out["action_average_precision"] = float("nan")
    return out


def json_safe(x):
    if isinstance(x, dict): return {str(k): json_safe(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)): return [json_safe(v) for v in x]
    if isinstance(x, (np.integer,)): return int(x)
    if isinstance(x, (np.floating, float)):
        v = float(x); return v if math.isfinite(v) else None
    return x
