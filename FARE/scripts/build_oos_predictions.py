#!/usr/bin/env python3
"""Strict paired OOF exporter from a planned, trained set of FARE v5.0.1 STLAformer folds.
The recommended automated entrypoint is scripts/submit_oof.py.
"""
import _bootstrap
import argparse,json
from pathlib import Path
from fare.oof import export_paired
from fare.config import project_path

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest',required=True,help='Fold plan generated by FARE 5.0.1')
    p.add_argument('--output',required=True)
    p.add_argument('--batch-size',type=int,default=16)
    a=p.parse_args()
    plan_path=project_path(a.manifest,must_exist=True)
    plan=json.loads(plan_path.read_text())
    producers=[plan_path.parent/f'fold_{fold["id"]:02d}'/'best.pt' for fold in plan['folds']]
    for f in producers:
        if not f.is_file():raise FileNotFoundError(f)
    export_paired(plan,producers,project_path(a.output),a.batch_size)
if __name__=='__main__':main()
